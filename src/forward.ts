/**
 * safesignal core: a forwarding client for the hosted
 * safe-check MCP server.
 *
 * Nothing about recalls or counterfeit risk is computed
 * here. tools/list is answered from the literal
 * definitions below, which reproduce a live capture of
 * the upstream server word for word (name, description
 * and inputSchema exactly as captured; the capture
 * carries NO title keys, and every tool requires
 * `query`). A tools/call travels upstream over a
 * streamable-HTTP JSON-RPC session: an initialize POST,
 * a notifications/initialized POST, then the tools/call
 * POST, carrying the Mcp-Session-Id response header on
 * later requests when the upstream issues one. The
 * session opens lazily on the first forwarded call and
 * is reused for the client's lifetime.
 *
 * The three captured tools all read published or
 * listing material: `recall_lookup` searches live US
 * government recall feeds and returns matching published
 * recall records with the official agency source link,
 * `counterfeit_risk` returns a risk level, score and
 * signals for a collectible product or listing (the
 * captured framing is "a risk SIGNAL, never proof of
 * fake"; the subject is a product/listing, never a
 * person), and `safe_check` runs the two reads in one
 * call. No payment, metering, contact, signup or send
 * tool exists in the surface.
 *
 * The endpoint is pinned to
 * https://safecheck.dropwatchhq.com/mcp and may be
 * replaced with the SAFECHECK_MCP_URL environment
 * variable (that override is a labelled reconstruction).
 * The registry record declares NO headers on the upstream
 * remote, so no auth header is ever sent, under any
 * environment.
 *
 * A successful upstream result is returned exactly as
 * received, isError flag and extra fields included.
 * Failures -- an upstream JSON-RPC error, a non-2xx
 * status, a body that cannot be parsed, or a fetch
 * that throws or times out -- become an isError result
 * whose text begins with `safesignal error:` (that
 * rendering is a labelled reconstruction). Replies may
 * be plain JSON or SSE (`data:` lines); the JSON-RPC
 * message whose id matches the request wins.
 */
